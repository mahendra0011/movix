const requestedUpcomingMovieSeeds = requestedUpcomingMovieRows.map(
  ([title, genreLabel, cast, releaseDate, language]) => {
    const genres = genreLabel.split(/\s+-\s+/).filter(Boolean);
    return {
      title,
      cast,
      industry: industryFor(language, genres),
      genres,
      language,
      releaseDate: releaseDate || "2026",
      releaseAt: releaseDate ? releaseAtFromLabel(releaseDate) : "",
    };
  },
);
const requestedComingSoonMovieSeeds = requestedUpcomingMovieSeeds;

function industryFor(language, genres) {
  const prefixByLanguage = {
    English: "Hollywood",
    Hindi: "Bollywood",
    Kannada: "Kannada",
    Malayalam: "Malayalam",
    Tamil: "Tamil",
    Telugu: "Telugu",
  };
  return `${prefixByLanguage[language] || language} / ${genres.slice(0, 2).join(" ")}`;
}

function releaseAtFromLabel(label) {
  const match = String(label || "").match(/^(\d{2})\s+([A-Za-z]+)\s+(\d{4})$/);
  if (!match) return "";

  const [, day, monthName, year] = match;
  const month = {
    jan: "01",
    feb: "02",
    mar: "03",
    apr: "04",
    may: "05",
    jun: "06",
    jul: "07",
    aug: "08",
    sep: "09",
    sept: "09",
    oct: "10",
    nov: "11",
    dec: "12",
  }[monthName.toLowerCase()];

  return month ? `${year}-${month}-${day}` : "";
}

export { requestedComingSoonMovieSeeds, requestedUpcomingMovieSeeds };
